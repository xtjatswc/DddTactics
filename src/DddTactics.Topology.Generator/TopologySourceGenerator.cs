using System.Collections.Immutable;
using System.Linq;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp.Syntax;
using Microsoft.CodeAnalysis.Text;

namespace DddTactics.Topology.Generator;

/// <summary>
/// 源生成器：扫描实现了 <c>DddTactics.EFCore.IDomainEventHandler&lt;TEvent&gt;</c> 的类，
/// 合并其上的 <see cref="DddTactics.Core.DispatchModeAttribute"/> 标注，生成拓扑注册代码（零结构标注）。
/// 聚合-事件-处理器关系的"结构"由本生成器自动产出；"策略"由 [DispatchMode] 显式标注。
/// </summary>
[Generator]
public sealed class TopologySourceGenerator : IIncrementalGenerator
{
    private const string HandlerInterfaceName = "IDomainEventHandler";
    private const string HandlerInterfaceNamespace = "DddTactics.EFCore";
    private const string DispatchModeAttributeName = "DispatchModeAttribute";
    private const string DispatchModeAttributeNamespace = "DddTactics.Core";

    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        var handlers = context.SyntaxProvider
            .CreateSyntaxProvider(
                predicate: static (node, _) => node is ClassDeclarationSyntax c && c.BaseList != null,
                transform: static (ctx, _) => GetHandlerInfo(ctx))
            .Where(static info => info is not null)
            .Select(static (info, _) => info!)
            .Collect();

        var globalOptions = context.AnalyzerConfigOptionsProvider.Select(static (o, _) => o.GlobalOptions);
        var combined = handlers.Combine(globalOptions);

        context.RegisterSourceOutput(combined, static (spc, pair) =>
        {
            var infos = pair.Left;
            var options = pair.Right;

            // 显式 MSBuild 回退：将 <EnableDddTacticsTopology>false</EnableDddTacticsTopology> 即可禁用生成器。
            if (options.TryGetValue("build_property.EnableDddTacticsTopology", out var enabled) && enabled == "false")
            {
                return;
            }

            if (infos.IsDefaultOrEmpty)
            {
                return;
            }

            var sb = new StringBuilder();
            sb.AppendLine("// <auto-generated/>");
            sb.AppendLine("#nullable enable");
            sb.AppendLine("namespace DddTactics.Topology.Generated;");
            sb.AppendLine("[global::System.Runtime.CompilerServices.CompilerGenerated]");
            sb.AppendLine("[global::DddTactics.Topology.TopologyRegistrationAttribute]");
            sb.AppendLine("public static class DddTacticsTopologyRegistration");
            sb.AppendLine("{");
            sb.AppendLine("    public static void Register(global::DddTactics.Topology.ITopologySink sink)");
            sb.AppendLine("    {");
            foreach (var info in infos)
            {
                sb.AppendLine($"        sink.AddHandler(@\"{info.EventFullName}\", @\"{info.HandlerFullName}\", @\"{info.Mode}\");");
            }

            sb.AppendLine("    }");
            sb.AppendLine("}");

            spc.AddSource("DddTacticsTopology.g.cs", SourceText.From(sb.ToString(), Encoding.UTF8));
        });
    }

    private static HandlerInfo? GetHandlerInfo(GeneratorSyntaxContext ctx)
    {
        var classDecl = (ClassDeclarationSyntax)ctx.Node;
        if (ctx.SemanticModel.GetDeclaredSymbol(classDecl) is not INamedTypeSymbol symbol)
        {
            return null;
        }

        INamedTypeSymbol? eventType = null;
        foreach (var iface in symbol.AllInterfaces)
        {
            if (!iface.IsGenericType)
            {
                continue;
            }

            if (iface.ConstructedFrom.Name != HandlerInterfaceName)
            {
                continue;
            }

            if (iface.ConstructedFrom.ContainingNamespace?.ToDisplayString() != HandlerInterfaceNamespace)
            {
                continue;
            }

            eventType = iface.TypeArguments[0] as INamedTypeSymbol;
            break;
        }

        if (eventType is null)
        {
            return null;
        }

        var mode = "None";
        foreach (var attr in symbol.GetAttributes())
        {
            if (attr.AttributeClass?.Name != DispatchModeAttributeName)
            {
                continue;
            }

            if (attr.AttributeClass.ContainingNamespace?.ToDisplayString() != DispatchModeAttributeNamespace)
            {
                continue;
            }

            var arg = attr.ConstructorArguments.Length > 0 ? attr.ConstructorArguments[0] : default;
            if (arg.Type is INamedTypeSymbol enumType && arg.Value is { } raw)
            {
                foreach (var field in enumType.GetMembers().OfType<IFieldSymbol>())
                {
                    if (field.ConstantValue is { } constant && constant.Equals(raw))
                    {
                        mode = field.Name;
                        break;
                    }
                }
            }

            if (mode == "None")
            {
                mode = arg.Value?.ToString() ?? "None";
            }

            break;
        }

        return new HandlerInfo(eventType.ToDisplayString(), symbol.ToDisplayString(), mode);
    }

    private sealed record HandlerInfo(string EventFullName, string HandlerFullName, string Mode);
}
